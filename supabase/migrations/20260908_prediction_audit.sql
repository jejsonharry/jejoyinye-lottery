-- Prediction Engine V2: immutable pre-draw forecasts and automatic scoring.
create table if not exists public.prediction_snapshots (
    id bigint generated by default as identity primary key,
    lottery text not null,
    game text not null,
    draw_date date not null,
    draw_time text,
    generated_at timestamptz not null default now(),
    engine_version text not null default 'v2.0',
    engine_profile text not null default 'balanced',
    range_from date,
    range_to date,
    sure_numbers integer[] not null,
    direct_numbers integer[] not null,
    all_numbers integer[] not null,
    score_details jsonb not null default '[]'::jsonb,
    weights jsonb not null default '{}'::jsonb,
    historical_draws integer not null default 0,
    backtest_draws integer not null default 0,
    backtest_score numeric not null default 0,
    backtest_hit_rate numeric not null default 0,
    actual_winning integer[],
    actual_machine integer[],
    sure_winning_hits integer[] not null default '{}'::integer[],
    direct_winning_hits integer[] not null default '{}'::integer[],
    machine_support_hits integer[] not null default '{}'::integer[],
    total_winning_hits integer not null default 0,
    sure_hit_count integer not null default 0,
    direct_hit_count integer not null default 0,
    machine_support_count integer not null default 0,
    status text not null default 'pending',
    evaluated_at timestamptz,
    constraint prediction_snapshots_unique_draw unique (lottery, game, draw_date),
    constraint prediction_snapshots_sure_count check (cardinality(sure_numbers) = 2),
    constraint prediction_snapshots_direct_count check (cardinality(direct_numbers) = 3),
    constraint prediction_snapshots_all_count check (cardinality(all_numbers) = 5),
    constraint prediction_snapshots_status check (status in ('pending', 'evaluated'))
);

create index if not exists prediction_snapshots_date_idx
    on public.prediction_snapshots (draw_date desc, lottery, game);

alter table public.prediction_snapshots enable row level security;

drop policy if exists "Public can read prediction snapshots" on public.prediction_snapshots;
create policy "Public can read prediction snapshots"
    on public.prediction_snapshots for select
    using (true);

drop policy if exists "Admins can manage prediction snapshots" on public.prediction_snapshots;
create policy "Admins can manage prediction snapshots"
    on public.prediction_snapshots for all
    using (public.is_admin())
    with check (public.is_admin());

grant select on public.prediction_snapshots to anon, authenticated;
grant insert, update, delete on public.prediction_snapshots to authenticated;
grant usage, select on sequence public.prediction_snapshots_id_seq to authenticated;

create or replace function public.evaluate_prediction_key(
    p_lottery text,
    p_game text,
    p_draw_date date
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    result_row public.results%rowtype;
    winning_numbers integer[] := '{}'::integer[];
    machine_numbers integer[] := '{}'::integer[];
begin
    select * into result_row
    from public.results
    where lottery = p_lottery
      and lower(trim(game)) = lower(trim(p_game))
      and draw_date = p_draw_date
    order by id desc
    limit 1;

    if not found then
        return;
    end if;

    select coalesce(array_agg(value::integer), '{}'::integer[])
      into winning_numbers
      from jsonb_array_elements_text(to_jsonb(result_row.winning));

    select coalesce(array_agg(value::integer), '{}'::integer[])
      into machine_numbers
      from jsonb_array_elements_text(coalesce(to_jsonb(result_row.machine), '[]'::jsonb));

    update public.prediction_snapshots as snapshot
       set actual_winning = winning_numbers,
           actual_machine = machine_numbers,
           sure_winning_hits = array(
               select number from unnest(snapshot.sure_numbers) as number
               where number = any(winning_numbers)
           ),
           direct_winning_hits = array(
               select number from unnest(snapshot.direct_numbers) as number
               where number = any(winning_numbers)
           ),
           machine_support_hits = array(
               select number from unnest(snapshot.all_numbers) as number
               where number = any(machine_numbers)
           ),
           total_winning_hits = cardinality(array(
               select number from unnest(snapshot.all_numbers) as number
               where number = any(winning_numbers)
           )),
           sure_hit_count = cardinality(array(
               select number from unnest(snapshot.sure_numbers) as number
               where number = any(winning_numbers)
           )),
           direct_hit_count = cardinality(array(
               select number from unnest(snapshot.direct_numbers) as number
               where number = any(winning_numbers)
           )),
           machine_support_count = cardinality(array(
               select number from unnest(snapshot.all_numbers) as number
               where number = any(machine_numbers)
           )),
           status = 'evaluated',
           evaluated_at = now()
     where snapshot.lottery = p_lottery
       and lower(trim(snapshot.game)) = lower(trim(p_game))
       and snapshot.draw_date = p_draw_date;
end;
$$;

create or replace function public.evaluate_prediction_from_result()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    perform public.evaluate_prediction_key(new.lottery, new.game, new.draw_date);
    return new;
end;
$$;

create or replace function public.evaluate_prediction_from_snapshot()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    perform public.evaluate_prediction_key(new.lottery, new.game, new.draw_date);
    return new;
end;
$$;

drop trigger if exists results_evaluate_prediction on public.results;
create trigger results_evaluate_prediction
after insert or update of winning, machine on public.results
for each row execute function public.evaluate_prediction_from_result();

drop trigger if exists snapshot_evaluate_existing_result on public.prediction_snapshots;
create trigger snapshot_evaluate_existing_result
after insert on public.prediction_snapshots
for each row execute function public.evaluate_prediction_from_snapshot();

